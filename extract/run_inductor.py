def parse_inductor_ops(yaml_path: Path) -> Dict[str, List[str]]:
    """Return {op_name: [benchmark_method_names]} for every pt2-tagged variant.

    Only includes variants whose tag list contains ``"pt2"`` (the convention
    for PyTorch Inductor compiled benchmarks in TritonBench).
    """
    with open(yaml_path) as f:
        metadata = yaml.safe_load(f) or {}

    inductor_ops: Dict[str, List[str]] = {}
    for op_name, variants in metadata.items():
        if not isinstance(variants, dict):
            continue
        pt2_impls = [
            name
            for name, meta in variants.items()
            if isinstance(meta, dict) and "pt2" in (meta.get("tags") or [])
        ]
        if pt2_impls:
            inductor_ops[op_name] = pt2_impls
    return inductor_ops


