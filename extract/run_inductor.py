"""
Capture Triton kernels generated by PyTorch Inductor, dump their IR and
input shapes, and register them in oss_cuda_kernels.yaml for the
multi-agent optimiser pipeline.

When an operator uses ``torch.compile(mode="max-autotune-no-cudagraphs")``
or ``inductor_config.patch(max_autotune=True)``, this script runs the
operator **with autotuning disabled** to capture the default heuristic
config.  The generated Triton kernel source, TTGIR, metadata, and input
shapes are saved to ``extract/ir_output/<device>/<operator>/`` in exactly
the same format that ``extract/run.py`` uses for hand-written Triton
kernels.

Usage:
    # Capture all inductor operators
    python extract/run_inductor.py --gpu v100 --output-dir ./ir_output

    # Specific operators only
    python extract/run_inductor.py --gpu v100 --ops softmax,vector_add

    # Limit to first N input configurations
    python extract/run_inductor.py --gpu v100 --num-inputs 3
"""

