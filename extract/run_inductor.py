def get_parser() -> argparse.ArgumentParser:
    parser = argparse.ArgumentParser(
        description=(
            "Capture Triton kernels generated by PyTorch Inductor, "
            "dump their IR and input shapes for multi-agent optimisation."
        ),
    )
    parser.add_argument(
        "--gpu", type=str, required=True,
        help="GPU name (e.g. v100, a100). Used as subfolder under output-dir.",
    )
    parser.add_argument(
        "--output-dir", type=str, default="ir_output",
        help="Output directory (relative to script dir). Default: ir_output",
    )
    parser.add_argument(
        "--ops", type=str, default=None,
        help="Comma-separated operators to process (default: all).",
    )
    parser.add_argument(
        "--metadata", type=str, default=str(OSS_CUDA_KERNELS_YAML),
        help="Path to oss_cuda_kernels.yaml.",
    )
    parser.add_argument(
        "--num-inputs", type=int, default=0,
        help="Number of input configs to process (0 = all available).",
    )
    parser.add_argument(
        "--device", type=str, default="cuda",
        help="Device to run on (default: cuda).",
    )
    # Internal flags for child-process mode
    parser.add_argument("--run-child", action="store_true",
                        help="(internal) Run as child process.")
    parser.add_argument("--op", type=str, default=None,
                        help="(internal) Operator name in child mode.")
    parser.add_argument("--only", type=str, default=None,
                        help="(internal) Comma-separated impl names.")
    parser.add_argument(
        "--clear-cache", action="store_true",
        help="Clear Triton JIT cache before extraction.",
    )
    return parser


if __name__ == "__main__":
    logging.basicConfig(
        level=logging.INFO,
        format="%(asctime)s %(message)s",
        datefmt="%H:%M:%S",
    )

    parser = get_parser()
    args = parser.parse_args()

    if getattr(args, "clear_cache", False) and not args.run_child:
        triton_cache = Path.home() / ".triton" / "cache"
        if triton_cache.exists():
            shutil.rmtree(triton_cache)
            logger.info("[inductor] Cleared Triton cache: %s", triton_cache)
        # Inductor's FX/compile cache short-circuits AlgorithmSelectorCache for
        # shapes seen in prior runs, which bypasses the choices[0] hook below
        # and returns the previously-cached autotune winner instead.
        from torch._inductor import codecache as _codecache
        inductor_cache = Path(_codecache.cache_dir())
        if inductor_cache.exists():
            shutil.rmtree(inductor_cache)
            logger.info("[inductor] Cleared Inductor compile cache: %s", inductor_cache)

    if args.run_child:
        run_child(args)
    else:
        run_parent(args)
