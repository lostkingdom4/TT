# Helpers — reused from extract/run.py to maintain format compatibility
# ---------------------------------------------------------------------------

def _shape_signature(tensor_args: list, scalar_args: list, grid) -> str:
    """Compute a hashable signature from tensor shapes/dtypes and scalar values.

    Note: grid is NOT included in the signature because autotuned kernels
    (like triton_mm) are launched repeatedly with the same tensors but different
    configs/grids during autotuning, which would otherwise create many duplicates.
    """
    parts = []
    for t in tensor_args:
        parts.append(f"{t['arg_index']}:{t['shape']}:{t['dtype']}")
    for s in scalar_args:
        parts.append(f"{s['arg_index']}:{s['value']}")
    return "|".join(parts)


def _normalize_grid(grid) -> object:
    """Convert a Triton grid value to a JSON-serialisable format."""
    if isinstance(grid, (tuple, list)):
        return list(grid)
    if callable(grid):
        try:
            import inspect
            return {"type": "callable", "source": inspect.getsource(grid)}
        except Exception:
            return {"type": "callable", "repr": str(grid)}
    return str(grid)


def _normalize_kwargs(kwargs: dict) -> dict:
    """Convert kernel kwargs to a JSON-serialisable dict, excluding 'grid'."""
    import torch

    info: Dict = {}
    for key, val in kwargs.items():
        if key == "grid":
            continue
        if isinstance(val, torch.Tensor):
            info[key] = {
                "type": "tensor",
                "shape": list(val.shape),
                "dtype": str(val.dtype),
                "device": str(val.device),
            }
        elif isinstance(val, (int, float, bool, str)):
            info[key] = {
                "type": "scalar",
                "value": val,
                "value_type": type(val).__name__,
            }
        else:
            info[key] = {
                "type": "other",
                "value": str(val),
                "value_type": type(val).__name__,
            }
    return info


# ---------------------------------------------------------------------------
# TTGIR loc() rewriting
# ---------------------------------------------------------------------------

def _rewrite_ttgir_locs(ttgir_content: str, old_source: str,
                        new_source: str) -> str:
    """Rewrite loc() attributes in TTGIR so they point to the saved source.

    Replaces every occurrence of the old source path with the new path in
    loc("path":line:col) attributes.
    """
    if not old_source or not new_source:
        return ttgir_content
    return ttgir_content.replace(old_source, new_source)


def _extract_source_paths_from_ttgir(ttgir_content: str) -> List[str]:
    """Extract all unique .py file paths from loc() attributes in TTGIR."""
    loc_pattern = r'loc\("([^"]+\.py)":(\d+):(\d+)\)'
    matches = re.findall(loc_pattern, ttgir_content)
    paths = set()
    # Filter out library / framework files
    _LIBRARY_MARKERS = ("site-packages", "dist-packages", "/lib/python")
    for path, _line, _col in matches:
        if not any(m in path for m in _LIBRARY_MARKERS):
            paths.add(path)
    return sorted(paths)


# ---------------------------------------------------------------------------
# Force Inductor's GEMM autotune to keep choices[0] as the "winner".
#
# We want the captured TTGIR to come from the first config in the predefined
# autotuning space (the canonical pre-tuning baseline), not the perf-winning
# config. The cleanest way is to narrow the choices list to [choices[0]]
# before Inductor benchmarks them: only one variant gets precompiled, no
# benchmarking happens, and the existing capture flow naturally records
# choices[0]'s .py snapshot and TTGIR.
#
# This is invariant across kernels — works for ``triton_mm`` templates,
# ``triton_tem_fused_*`` fused templates, and any other ChoiceCaller list
# Inductor's algorithm selector receives.
# ---------------------------------------------------------------------------

def _install_first_choice_autotune():
    """Monkey-patch ``AlgorithmSelectorCache.__call__`` to keep only choices[0].

    Returns a restore() callable that undoes the patch.
    """
    from torch._inductor import select_algorithm as _sa

    original_call = _sa.AlgorithmSelectorCache.__call__

    def first_choice_call(self, name, choices, *args, **kwargs):
        if choices:
            # Keep only the first candidate. Inductor will skip benchmarking
            # (only one option to pick) and emit/compile that one config.
            choices = [choices[0]]
        return original_call(self, name, choices, *args, **kwargs)

    _sa.AlgorithmSelectorCache.__call__ = first_choice_call

    def restore():
        _sa.AlgorithmSelectorCache.__call__ = original_call

    return restore


# ---------------------------------------------------------------------------
# Kernel shape saving — mirrors extract/run.py::_save_kernel_shapes
# ---------------------------------------------------------------------------

def _save_kernel_shapes(captured: Dict[str, List[dict]], op_name: str,
                        output_dir: Path) -> None:
    """Write per-kernel, per-input shape files.

    File naming matches extract/run.py conventions so that
    ``multiagent_triton_runner._find_shapes()`` discovers them.
    """
    output_dir.mkdir(parents=True, exist_ok=True)

    for kname, shape_list in captured.items():
        if not shape_list:
            continue

        # Backward-compatible default (= input 0)
        default_filename = f"{op_name}_{kname}_shapes.json"
        default_path = output_dir / default_filename
        with open(default_path, "w") as f:
            json.dump(shape_list[0], f, indent=2)
        logger.info("Saved default shapes: %s", default_path)

        # Per-input files
        for i, meta in enumerate(shape_list):
            per_input_path = output_dir / f"{op_name}_{kname}_input{i}_shapes.json"
            with open(per_input_path, "w") as f:
                json.dump(meta, f, indent=2)

        logger.info("Saved %d per-input shape files for %s", len(shape_list), kname)


# ---------------------------------------------------------------------------
# YAML update — add captured kernel names under pt2 variants
# ---------------------------------------------------------------------------

def _update_yaml_with_kernels(yaml_path: Path, op_name: str,
                               impl_name: str,
                               kernel_names: List[str]) -> None:
    """Add ``kernels`` entries to a pt2 variant in oss_cuda_kernels.yaml.

    Preserves existing YAML structure; only adds/extends the ``kernels``
    list under the specified operator / implementation.
    """
    with open(yaml_path) as f:
        metadata = yaml.safe_load(f) or {}

    if op_name not in metadata:
        metadata[op_name] = {}
    if impl_name not in metadata[op_name]:
        metadata[op_name][impl_name] = {"tags": ["pt2"]}

    variant = metadata[op_name][impl_name]
    existing = set(variant.get("kernels") or [])
    new_kernels = existing | set(kernel_names)
    variant["kernels"] = sorted(new_kernels)

    # Ensure pt2 tag is present
    tags = variant.get("tags") or []
    if "pt2" not in tags:
        tags.append("pt2")
    variant["tags"] = tags

    with open(yaml_path, "w") as f:
        yaml.dump(metadata, f, default_flow_style=False, sort_keys=True)

    logger.info("Updated YAML: %s.%s -> kernels=%s",
                op_name, impl_name, sorted(new_kernels))


# ---------------------------------------------------------------------------
# Core: capture inductor kernels for a single operator + impl
# ---------------------------------------------------------------------------

def _capture_inductor_kernels(
    op_name: str,
    impl_name: str,
    output_dir: Path,
    num_inputs: int = 0,
    device: str = "cuda",
) -> Dict[str, List[dict]]:
    """Run an inductor benchmark with autotuning disabled and capture kernels.

    Hooks ``CachingAutotuner.run`` (the inductor's kernel launch wrapper)
    to intercept all Triton kernel launches.  PyTorch Inductor does NOT use
    ``JITFunction.run`` — it compiles and launches kernels via its own
    ``CachingAutotuner`` mechanism from ``torch._inductor.runtime``.

    Extracts TTGIR from Triton's compilation cache.
    Saves generated Triton source with loc() rewriting.

    Returns dict mapping kernel_name -> list of shape metadata dicts.
    """
    import torch
    import torch._inductor.config as inductor_config
    from torch._inductor.runtime.triton_heuristics import CachingAutotuner
    from tritonbench.operators import load_opbench_by_name
    from tritonbench.utils.parser import get_parser

    # Use a fresh Triton cache so we can extract TTGIR afterwards
    triton_cache_dir = tempfile.mkdtemp(prefix="triton_cache_inductor_")
    os.environ["TRITON_CACHE_DIR"] = triton_cache_dir

    # Build TritonBench args
    needs_autotune = "maxautotune" in impl_name.lower()
    precision = _PRECISION_OVERRIDE.get(op_name, "fp16")
    parser = get_parser()
    tb_args_list = [
        "--device", device,
        "--precision", precision,
        "--metrics", "latency",
        "--only", impl_name,
    ]
    # Force-enable benchmarks registered with enabled=False (e.g. maxautotune)
    if needs_autotune:
        tb_args_list.append("--force")
    if num_inputs > 0:
        tb_args_list.extend(["--num-inputs", str(num_inputs)])
    tb_args, extra_args = parser.parse_known_args(tb_args_list)
    tb_args.warmup = 0
    tb_args.rep = 1

    # Load operator
    OpClass = load_opbench_by_name(op_name)
    if OpClass is None:
        raise RuntimeError(f"Operator '{op_name}' not found in TritonBench")

    # Capture state
    captured: Dict[str, List[dict]] = {}
    seen_sigs: Dict[str, set] = {}
    # Track source filenames per kernel for TTGIR extraction
    kernel_source_files: Dict[str, str] = {}
    original_run = CachingAutotuner.run

    def capture_run(self, *args, grid, stream, benchmark_run=False, **kwargs):
        # Call the original first, which triggers precompilation
        result = original_run(
            self, *args, grid=grid, stream=stream,
            benchmark_run=benchmark_run, **kwargs,
        )

        try:
            kname = getattr(getattr(self, "fn", None), "__name__", "unknown")

            # Capture tensor/scalar args
            tensor_args = []
            scalar_args = []
            for idx, arg in enumerate(args):
                if isinstance(arg, torch.Tensor):
                    tensor_args.append({
                        "arg_index": idx,
                        "shape": list(arg.shape),
                        "dtype": str(arg.dtype),
                        "device": str(arg.device),
                        "numel": int(arg.numel()),
                        "stride": list(arg.stride()),
                        "is_contiguous": bool(arg.is_contiguous()),
                    })
                elif isinstance(arg, (int, float, bool)):
                    scalar_args.append({
                        "arg_index": idx,
                        "value": arg,
                        "type": type(arg).__name__,
                    })

            # Extract config from launcher (available after precompilation)
            config_kwargs: Dict[str, Any] = {}
            if hasattr(self, "launchers") and self.launchers:
                cfg = self.launchers[0].config
                config_kwargs = {
                    k: {"type": "scalar", "value": v,
                         "value_type": type(v).__name__}
                    for k, v in cfg.kwargs.items()
                }
                config_kwargs["num_warps"] = {
                    "type": "scalar", "value": cfg.num_warps,
                    "value_type": "int",
                }
                config_kwargs["num_stages"] = {
                    "type": "scalar", "value": cfg.num_stages,
                    "value_type": "int",
                }

            # Evaluate grid
            grid_val = grid
            if callable(grid):
                try:
                    launcher_cfg = {}
                    if hasattr(self, "launchers") and self.launchers:
                        launcher_cfg = dict(self.launchers[0].config.kwargs)
                    grid_val = grid(launcher_cfg)
                except Exception:
                    grid_val = str(grid)

            sig = _shape_signature(tensor_args, scalar_args, grid_val)
            if kname not in seen_sigs:
                seen_sigs[kname] = set()
                captured[kname] = []

            if sig not in seen_sigs[kname]:
                seen_sigs[kname].add(sig)
                captured[kname].append({
                    "kernel": kname,
                    "tensor_args": tensor_args,
                    "scalar_args": scalar_args,
                    "kwargs": config_kwargs,
                    "grid": _normalize_grid(grid_val),
                    "total_args": len(args),
                    "input_index": len(captured[kname]),
                })

            # Record source filename for later TTGIR extraction. ``self.filename``
            # is ``None`` on Inductor's CachingAutotuner instances; fall back to
            # the wrapped JITFunction's underlying Python function, whose
            # __code__.co_filename points at the generated .py.
            src_file = getattr(self, "filename", None)
            if not src_file:
                inner_fn = getattr(self, "fn", None)
                wrapped = getattr(inner_fn, "fn", None)
                code = getattr(wrapped, "__code__", None)
                if code is not None:
                    src_file = getattr(code, "co_filename", None)
            if src_file and kname not in kernel_source_files:
                kernel_source_files[kname] = src_file

            # Save per-input kernel source. Read the file into memory *now* —
            # Inductor's compile cache may reuse the same path for the next
            # call site and overwrite its contents before we'd otherwise copy.
            # Two cases need per-input snapshots:
            #   1. Template kernels — bake M/N/K/strides as integer literals.
            #   2. Pointwise/reduction kernels with baked numel literals
            #      (e.g. ``xnumel = 4294967296`` reassignment in the @triton.jit
            #      body, or a literal ``size_hints={'x': N}`` in the decorator).
            #      Under ``max_autotune=True`` Inductor specializes for the
            #      worst-case xnumel from FX-graph analysis instead of the
            #      actual call-site xnumel; without per-input capture the
            #      runner reuses that bogus bound and over-launches the grid.
            _BAKED_NUMEL_RE = re.compile(
                r"^\s*[xyrz]numel\s*=\s*\d+", re.MULTILINE
            )
            if src_file:
                snapshot = None
                try:
                    snapshot = Path(src_file).read_text()
                except (OSError, IOError) as snap_err:
                    logger.warning(
                        "Failed to read %s for per-input snapshot: %s",
                        src_file, snap_err,
                    )
                needs_per_input = bool(snapshot) and (
                    "triton_heuristics.template(" in snapshot
                    or _BAKED_NUMEL_RE.search(snapshot) is not None
                )
                if needs_per_input:
                    input_idx = len(captured[kname]) - 1
                    per_input_dest = output_dir / f"{kname}_input{input_idx}.py"
                    try:
                        output_dir.mkdir(parents=True, exist_ok=True)
                        per_input_dest.write_text(snapshot)
                    except (OSError, IOError) as write_err:
                        logger.warning(
                            "Failed to write per-input source %s: %s",
                            per_input_dest, write_err,
                        )

        except Exception as capture_err:
            # Never let capture break kernel execution, but surface the error.
            logger.warning(
                "Capture hook failed for kernel launch: %s", capture_err,
            )

        return result

    skip_autotune = op_name in _SKIP_MAX_AUTOTUNE
    if skip_autotune:
        logger.info(
            "Skipping max_autotune for %s.%s (operator is in _SKIP_MAX_AUTOTUNE "
            "— preserves standalone pointwise epilogue kernels)",
            op_name, impl_name,
        )
    else:
        logger.info(
            "Forcing max_autotune+TRITON-only GEMM for %s.%s "
            "(autotune narrowed to choices[0] for pre-tuning baseline)",
            op_name, impl_name,
        )

    CachingAutotuner.run = capture_run
    restore_first_choice = (
        (lambda: None) if skip_autotune else _install_first_choice_autotune()
    )
    try:
        # Reset dynamo to avoid cached compilations
        torch._dynamo.reset()

        if skip_autotune:
            op = OpClass(tb_args=tb_args, extra_args=extra_args)
            op.run(warmup=0, rep=1)
        else:
            # coordinate_descent_tuning=False makes the captured baseline a
            # deterministic function of the input shape. With it enabled,
            # Inductor's coordinate-descent search runs *after* the autotune
            # winner is picked and mutates around the winner, so the kwargs
            # we capture depend on per-call timing noise. Disabling it means
            # choices[0] is the baseline — same shape file always yields the
            # same kwargs across re-extracts.
            with inductor_config.patch(
                max_autotune=True,
                max_autotune_gemm_backends="TRITON",
                coordinate_descent_tuning=False,
            ):
                op = OpClass(tb_args=tb_args, extra_args=extra_args)
                op.run(warmup=0, rep=1)
    finally:
        CachingAutotuner.run = original_run
        restore_first_choice()

    if not captured:
        logger.warning("No kernels captured for %s.%s", op_name, impl_name)
        return {}

    logger.info("Captured %d unique kernels for %s.%s: %s",
                len(captured), op_name, impl_name, list(captured.keys()))

    # --- Save TTGIR, source, and metadata from Triton cache ---
    output_dir.mkdir(parents=True, exist_ok=True)

    for kname in captured:
        _extract_and_save_ir(
            kname, triton_cache_dir, output_dir, op_name,
        )

    # Cleanup triton cache
    try:
        shutil.rmtree(triton_cache_dir)
    except Exception:
        pass

    return captured


def _extract_and_save_ir(
    kernel_name: str,
    triton_cache_dir: str,
    output_dir: Path,
    op_name: str,
) -> None:
    """Extract TTGIR/TTIR from Triton's compilation cache and save with
    rewritten loc() paths.

    Also saves the generated Triton source code to a persistent location.
    """
    cache_path = Path(triton_cache_dir)

    # Find TTGIR files matching this kernel
    ttgir_files = sorted(cache_path.rglob("*.ttgir"))
    ttir_files = sorted(cache_path.rglob("*.ttir"))

    # Match TTGIR to kernel name by reading content
    matched_ttgir = None
    for tf in ttgir_files:
        content = tf.read_text(errors="ignore")
        if kernel_name in content or f"@{kernel_name}" in content:
            matched_ttgir = tf
            break

    if matched_ttgir is None:
        # Fallback: try matching by directory name
        for tf in ttgir_files:
            if kernel_name in str(tf):
                matched_ttgir = tf
                break

    if matched_ttgir is None:
        logger.warning("No TTGIR found for kernel %s in cache %s",
                       kernel_name, triton_cache_dir)
        return

    ttgir_content = matched_ttgir.read_text()
    logger.info("Found TTGIR for %s: %s (%d bytes)",
                kernel_name, matched_ttgir, len(ttgir_content))

    # Find and save the generated Triton source
    source_paths = _extract_source_paths_from_ttgir(ttgir_content)
    saved_source_path = None

    for src_path in source_paths:
        src = Path(src_path)
        if src.exists():
            # Save a copy of the generated source to the output directory
            dest = output_dir / f"{kernel_name}.py"
            shutil.copy2(str(src), str(dest))
            saved_source_path = str(dest)
            logger.info("Saved generated source: %s -> %s", src_path, dest)

            # Rewrite loc() paths in TTGIR
            ttgir_content = _rewrite_ttgir_locs(
                ttgir_content, src_path, saved_source_path
            )
            break

    if saved_source_path is None:
        logger.warning("Could not find/save source for kernel %s "
                       "(loc paths: %s)", kernel_name, source_paths)

    # Save TTGIR
    ttgir_out = output_dir / f"{op_name}_{kernel_name}.ttgir"
    ttgir_out.write_text(ttgir_content)
    logger.info("Saved TTGIR: %s", ttgir_out)

    # Save TTIR (if available)
    matched_ttir = None
    for tf in ttir_files:
        content = tf.read_text(errors="ignore")
        if kernel_name in content or f"@{kernel_name}" in content:
            matched_ttir = tf
            break
    if matched_ttir is None:
        for tf in ttir_files:
            if kernel_name in str(tf):
                matched_ttir = tf
                break

    if matched_ttir is not None:
        ttir_out = output_dir / f"{op_name}_{kernel_name}.ttir"
        shutil.copy2(str(matched_ttir), str(ttir_out))
        logger.info("Saved TTIR: %s", ttir_out)

    # Save metadata JSON
    metadata = {
        "name": kernel_name,
        "operator": op_name,
        "is_inductor_generated": True,
        "arch": "",
        "shared": 0,
    }
    meta_out = output_dir / f"{op_name}_{kernel_name}.json"
    with open(meta_out, "w") as f:
        json.dump(metadata, f, indent=2)
    logger.info("Saved metadata: %s", meta_out)


# ---------------------------------------------------------------------------
# Child-process entry: capture kernels for a single operator
# ---------------------------------------------------------------------------

def run_child(args: argparse.Namespace) -> None:
    """Child-process entry: capture inductor kernels for a single operator."""
    output_dir = Path(args.output_dir) / args.gpu
    op_name = args.op
    impl_names = args.only.split(",") if args.only else []
    num_inputs = getattr(args, "num_inputs", 0)
    op_dir = output_dir / op_name
    op_dir.mkdir(parents=True, exist_ok=True)

    if not impl_names:
        # Discover pt2 impls from YAML
        inductor_ops = parse_inductor_ops(Path(args.metadata))
        impl_names = inductor_ops.get(op_name, [])

    if not impl_names:
        logger.warning("No pt2 implementations found for %s", op_name)
        return

    all_captured_kernels: Dict[str, List[str]] = {}  # impl -> kernel names

    for impl_name in impl_names:
        logger.info("[inductor] Capturing %s.%s (num_inputs=%s) ...",
                    op_name, impl_name, num_inputs or "all")
        try:
            captured = _capture_inductor_kernels(
                op_name, impl_name, op_dir,
                num_inputs=num_inputs,
                device=args.device if hasattr(args, "device") else "cuda",
            )

            if captured:
                # Save shapes
                _save_kernel_shapes(captured, op_name, op_dir)
                all_captured_kernels[impl_name] = list(captured.keys())
                logger.info("[inductor] Captured kernels for %s.%s: %s",
                            op_name, impl_name, list(captured.keys()))
            else:
                logger.warning("[inductor] No kernels captured for %s.%s",
                               op_name, impl_name)
        except Exception as exc:
            logger.warning("[inductor] Failed to capture %s.%s: %s",
                           op_name, impl_name, exc)
            import traceback
            traceback.print_exc()

    # Update YAML with captured kernel names
    for impl_name, kernel_names in all_captured_kernels.items():
        if kernel_names:
            _update_yaml_with_kernels(
                Path(args.metadata), op_name, impl_name, kernel_names,
            )

    logger.info("[inductor] Done with %s. Captured kernels: %s",
                op_name, all_captured_kernels)


# ---------------------------------------------------------------------------
# Parent-process: orchestrate children
# ---------------------------------------------------------------------------

def spawn_child(op_name: str, impl_names: List[str], output_dir: Path,
                num_inputs: int = 0, gpu: str = "",
                metadata: str = "") -> None:
    """Spawn a child subprocess for a single operator (GPU isolation)."""
    cmd = [
        sys.executable,
        str(SCRIPT_PATH),
        "--run-child",
        "--gpu", gpu,
        "--op", op_name,
        "--only", ",".join(impl_names),
        "--output-dir", str(output_dir),
        "--num-inputs", str(num_inputs),
        "--metadata", metadata,
    ]
    logger.info("[inductor] Starting: %s", " ".join(cmd))
    start = time.perf_counter()
    try:
        subprocess.check_call(
            cmd,
            stdout=sys.stdout,
            stderr=sys.stderr,
            cwd=str(REPO_PATH),
        )
        elapsed = time.perf_counter() - start
        logger.info("[inductor] Finished %s in %.1fs", op_name, elapsed)
    except subprocess.CalledProcessError:
        logger.warning("[inductor] Failed for %s, continuing ...", op_name)
    except KeyboardInterrupt:
        logger.warning("[inductor] Interrupted, exiting.")
        sys.exit(1)


def _resolve_output_dir(raw: str) -> Path:
    """Resolve output dir relative to the script's directory."""
    p = Path(raw)
    if p.is_absolute():
        return p
    return (SCRIPT_DIR / p).resolve()


def run_parent(args: argparse.Namespace) -> None:
    """Parse YAML, filter operators, and spawn a child per operator."""
    output_dir = _resolve_output_dir(args.output_dir) / args.gpu
    output_dir.mkdir(parents=True, exist_ok=True)

    inductor_ops = parse_inductor_ops(Path(args.metadata))
    if not inductor_ops:
        logger.error("[inductor] No pt2-tagged operators found in %s",
                     args.metadata)
        sys.exit(0)

    if args.ops:
        requested = set(args.ops.split(","))
        inductor_ops = {k: v for k, v in inductor_ops.items()
                        if k in requested}
        missing = requested - set(inductor_ops.keys())
        if missing:
            logger.warning("[inductor] Operators not found in YAML: %s",
                           missing)

    # Filter out operators incompatible with the target GPU
    gpu_skip = _GPU_SKIP.get(args.gpu, {})
    skipped = {k: reason for k, reason in gpu_skip.items()
               if k in inductor_ops}
    if skipped:
        for op, reason in sorted(skipped.items()):
            logger.info("[inductor] Skipping %s: %s", op, reason)
        inductor_ops = {k: v for k, v in inductor_ops.items()
                        if k not in gpu_skip}

    logger.info("[inductor] Found %d inductor-tagged operators:",
                len(inductor_ops))
    for op_name, impls in inductor_ops.items():
        logger.info("  %s: %s", op_name, impls)

    for op_name, impls in inductor_ops.items():
        logger.info("\n[inductor] ===== %s =====", op_name)
        spawn_child(
            op_name, impls, _resolve_output_dir(args.output_dir),
            num_inputs=args.num_inputs, gpu=args.gpu,
            metadata=args.metadata,
        )

    logger.info("\n[inductor] Done. Results saved to %s", output_dir)


